"""Builds the stat sheet (stats/STAT_SHEET.md) from every eval run in stats/runs.jsonl.

  python tools/stats.py

What it shows:
  1. Baselines: the untouched base models (label "baseline"). Everything is measured against these.
  2. Development log: every run in order, with the change vs. the matching baseline.
  3. Gap closed: how far 7B + StreamCoder has moved toward the plain 14B score.
       0% = no better than plain 7B, 100% = matches plain 14B, >100% = beats it.
  4. Category comparison: published scores of similar-size models from stats/category.yaml.
"""
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
RUNS = ROOT / "stats" / "runs.jsonl"
CATEGORY = ROOT / "stats" / "category.yaml"
OUT = ROOT / "stats" / "STAT_SHEET.md"


def pct(x):
    return "–" if x is None else f"{x:.0%}"


def delta(x, base):
    if x is None or base is None:
        return "–"
    d = (x - base) * 100
    return f"{d:+.0f} pts"


def num(x, fmt="{:.1f}"):
    return "–" if x is None else fmt.format(x)


def main():
    runs = [json.loads(l) for l in RUNS.read_text().splitlines() if l.strip()] if RUNS.exists() else []
    lines = ["# StreamCoder stat sheet", "",
             "_Generated by `python tools/stats.py`. Don't edit by hand; edit stats/category.yaml._", ""]
    if not runs:
        lines += ["No runs yet. Start with:", "",
                  "    python -m src.eval --model 7b --label baseline --model-file <file.gguf>", ""]
        OUT.write_text("\n".join(lines))
        print(f"wrote {OUT.relative_to(ROOT)} (empty)")
        return

    # first plain run labeled "baseline" per model key
    base = {}
    for r in runs:
        if r["label"] == "baseline" and r["mode"] == "plain":
            base.setdefault(r["model"], r)

    lines += ["## 1. Baselines (untouched base models)", "",
              "| Model | File | Pass | Easy | Hard | Sec/task | Tok/s | Peak VRAM | Date |",
              "|---|---|---|---|---|---|---|---|---|"]
    for m, r in base.items():
        lines.append(f"| {m} | {r['model_file'] or '–'} | {pct(r['pass_rate'])} | {pct(r['easy'])} | "
                     f"{pct(r['hard'])} | {num(r['avg_seconds'])} | {num(r['tokens_per_sec'])} | "
                     f"{num(r['peak_vram_mb'], '{:,} MB')} | {r['date']} |")
    if not base:
        lines.append("| _missing: run with `--label baseline` first_ | | | | | | | | |")

    lines += ["", "## 2. Development log", "",
              "| # | Date | Change (label) | Model | Mode | Tasks | Pass | vs baseline | Hard | TS / React / Node | Sec/task | Tok/s | VRAM | Commit |",
              "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for i, r in enumerate(runs, 1):
        b = base.get(r["model"])
        lines.append(f"| {i} | {r['date']} | {r['label']} | {r['model']} | {r['mode']} | {r['tasks']} | {pct(r['pass_rate'])} | "
                     f"{delta(r['pass_rate'], b and b['pass_rate'])} | {pct(r['hard'])} | "
                     f"{pct(r.get('typescript'))} / {pct(r.get('react'))} / {pct(r.get('node'))} | {num(r['avg_seconds'])} | "
                     f"{num(r['tokens_per_sec'])} | {num(r['peak_vram_mb'], '{:,}')} | {r.get('commit') or '–'} |")

    lines += ["", "## 3. Gap closed: 7B + StreamCoder vs plain 14B", ""]
    b7, b14 = base.get("7b"), base.get("14b")
    stream7 = [r for r in runs if r["model"] == "7b" and r["mode"] == "stream"]
    if b7 and b14 and stream7 and b14["pass_rate"] != b7["pass_rate"]:
        best = max(stream7, key=lambda r: r["pass_rate"])
        gap = (best["pass_rate"] - b7["pass_rate"]) / (b14["pass_rate"] - b7["pass_rate"])
        lines += [f"- Plain 7B: **{pct(b7['pass_rate'])}** | plain 14B: **{pct(b14['pass_rate'])}** | "
                  f"best 7B + StreamCoder: **{pct(best['pass_rate'])}** ({best['label']})",
                  f"- **Gap closed: {gap:.0%}**",
                  f"- Speed: {num(best['avg_seconds'])}s/task vs 14B {num(b14['avg_seconds'])}s/task | "
                  f"VRAM: {num(best['peak_vram_mb'], '{:,}')} vs {num(b14['peak_vram_mb'], '{:,}')} MB"]
    else:
        lines.append("Needs: a 7B baseline, a 14B baseline, and at least one 7B `--stream` run.")

    lines += ["", "## 4. Category comparison (published scores, same size class)", "",
              "Our eval is custom, so it can't be compared directly with public numbers. "
              "To compare, run the same public benchmark (e.g. HumanEval) on your setup and log it here.", "",
              "| Model | Params | Quant | Benchmark | Score | Source |", "|---|---|---|---|---|---|"]
    cat = (yaml.safe_load(CATEGORY.read_text()) or {}).get("models", []) if CATEGORY.exists() else []
    for c in cat:
        lines.append(f"| {c.get('name')} | {c.get('params')} | {c.get('quant', '–')} | {c.get('benchmark')} | "
                     f"{c.get('score')} | {c.get('source', '–')} |")
    if not cat:
        lines.append("| _add entries to stats/category.yaml_ | | | | | |")

    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(runs)} runs)")


if __name__ == "__main__":
    sys.exit(main())
